/**
 * Embeds the two Inter faces the printable QR card draws its text with.
 *
 * The card used to write its text as SVG `<text font-family="Arial…">`. That rasterised on a
 * developer's Windows machine, where Arial exists, and rendered as nothing on the Linux host the
 * product runs on, which has no fonts at all — the first printed PNG from production had no
 * business name and no credit. Text is now converted to paths with a bundled font, so the
 * PNG is the same bytes on every host, and the font ships inside the code rather than as a file
 * a serverless bundle might not carry.
 *
 * Source: @fontsource/inter 5.2.5, latin subset, WOFF (opentype.js reads WOFF 1.0, not WOFF2).
 * Licence: SIL Open Font License 1.1 — apps/web/assets/fonts/LICENSE.inter.txt.
 *
 *   node scripts/generate-qr-card-fonts.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const faces = [
  ['semibold', 'inter-latin-600-normal.woff', 600],
  ['extrabold', 'inter-latin-800-normal.woff', 800],
];

const lines = [
  '// Generated by scripts/generate-qr-card-fonts.mjs — do not edit.',
  '// Inter (SIL OFL 1.1), latin subset, from @fontsource/inter 5.2.5. See assets/fonts/LICENSE.inter.txt.',
  '',
];
for (const [name, file, weight] of faces) {
  const bytes = readFileSync(`${root}apps/web/assets/fonts/${file}`);
  lines.push(`/** Inter ${weight}, WOFF, base64 (${bytes.length} bytes). */`);
  lines.push(`export const INTER_${name.toUpperCase()}_WOFF_BASE64 =`);
  lines.push(`  '${bytes.toString('base64')}';`);
  lines.push('');
}
writeFileSync(`${root}apps/web/lib/qr-card-fonts.generated.ts`, lines.join('\n'));
console.log('wrote apps/web/lib/qr-card-fonts.generated.ts');
